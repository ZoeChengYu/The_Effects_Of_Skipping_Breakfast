def get_price(name):
    name = name.strip()
    if name in prices:
        val = prices[name]
        if isinstance(val, dict):
            return None
        return val
    # Check prefixes/suffixes
    for base, sub_prices in prices.items():
        if isinstance(sub_prices, dict) and base in name:
            if '湯種' in name:
                return sub_prices.get('toast')
            elif '丹麥' in name:
                return sub_prices.get('danemark')
            elif '可頌' in name:
                return sub_prices.get('croissant')
            elif '漢堡' in name or '堡' in name:
                return sub_prices.get('burger')
    return None


